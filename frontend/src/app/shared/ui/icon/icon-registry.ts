export type IconName = keyof typeof ICON_REGISTRY;

const ACTIVE_SUFFIX = 'Active';

export function svgFor(name: string): string | null {
  const active = name.endsWith(ACTIVE_SUFFIX);
  const base = active ? name.slice(0, -ACTIVE_SUFFIX.length) : name;
  const def: IconDef | undefined = ICON_REGISTRY[base as IconName];
  if (!def) return null;
  return (active && def.active) || def.outline;
}
